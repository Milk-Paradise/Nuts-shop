import type { Product, ProductVariant } from "../model/types";
// Demo prices and availability. Replace only through the validated backend adapter.
function variants(
  id: string,
  price: number,
  colors: [string, string][],
  storage = ["128 ГБ", "256 ГБ", "512 ГБ"],
): ProductVariant[] {
  return colors.flatMap(([color, colorHex], ci) =>
    storage.map((size, si) => ({
      id: `${id}-${ci}-${si}`,
      label: `${color}, ${size}`,
      color,
      colorHex,
      storage: size,
      price: price + si * 12000,
      stock: 10,
    })),
  );
}
